"""Gera welcome e Snapshot de uma Room coop sem servidor."""
import argparse
import json
from pathlib import Path

from app.game import (
	TICK_RATE, Input, InvalidMapError, MapNotFoundError, Mode, RoomOptions,
	create_room, enqueue, initial_grid, last_input_seq, load_map,
	set_connected, step, to_snapshot,
)
from app.game.protocol import encode_welcome, snapshot_encoder


KEYS = ("up", "down", "left", "right", "rot_left", "rot_right", "sprint")


def non_negative(value: str) -> int:
	number = int(value)
	if number < 0:
		raise argparse.ArgumentTypeError("must be zero or greater")
	return number


def main(argv: list[str] | None = None) -> None:
	parser = argparse.ArgumentParser(description=__doc__)
	parser.add_argument("--map", default="dungeon_map")
	parser.add_argument("--ticks", type=non_negative, default=300)
	parser.add_argument("--players", type=int, choices=range(1, 6), default=5)
	parser.add_argument("--seed", type=int, default=1)
	parser.add_argument("--keys", nargs="*", choices=KEYS, default=["up"])
	parser.add_argument("--output", type=Path, default=Path("snapshot.json"))
	args = parser.parse_args(argv)

	try:
		game_map = load_map(args.map, Mode.COOP)
		options = RoomOptions()
		players = [
			(user_id, f"player_{user_id}")
			for user_id in range(1, args.players + 1)
		]
		room = create_room(
			1, Mode.COOP, game_map, options, players, args.seed,
		)
		for user_id, _ in players:
			set_connected(room, user_id, True)

		user_id = players[0][0]
		welcome = json.loads(encode_welcome(
			user_id=user_id,
			match_id=1,
			mode=Mode.COOP,
			map_name=game_map.name,
			options=options,
			grid=initial_grid(room),
			snapshot=to_snapshot(room),
			last_input_seq=last_input_seq(room, user_id),
		))

		held = {key: key in args.keys for key in KEYS}
		for seq in range(1, args.ticks + 1):
			for player_id, _ in players:
				enqueue(room, player_id, Input(
					seq=seq, mouse_dx=0.0, **held,
				))
			step(room, 1 / TICK_RATE)

		snapshot = json.loads(snapshot_encoder(to_snapshot(room))(
			last_input_seq(room, user_id),
		))
		document = {
			"about": "Generated by the Simulation CLI.",
			"welcome": welcome,
			"snapshot": snapshot,
		}
		args.output.write_text(
			json.dumps(document, indent=2, ensure_ascii=False, allow_nan=False)
			+ "\n",
			encoding="utf-8",
		)
	except (MapNotFoundError, InvalidMapError, OSError) as error:
		parser.error(str(error))


if __name__ == "__main__":
	main()
